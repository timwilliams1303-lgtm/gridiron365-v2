-- 8. SUPABASE REALTIME
--
-- This gives us the same live-update foundation we established
-- for NFL.
-- ============================================================

do $$
begin

    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'nhl_teams'
    ) then
        execute
            'alter publication supabase_realtime add table public.nhl_teams';
    end if;


    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'nhl_players'
    ) then
        execute
            'alter publication supabase_realtime add table public.nhl_players';
    end if;


    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'nhl_games'
    ) then
        execute
            'alter publication supabase_realtime add table public.nhl_games';
    end if;


    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'nhl_player_game_stats'
