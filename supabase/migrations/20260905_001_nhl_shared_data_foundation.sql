-- ============================================================
-- 1. NHL TEAMS
-- ============================================================

create table if not exists public.nhl_teams (
    id bigint generated by default as identity primary key,

    espn_team_id text unique,

    abbreviation text not null,
    name text not null,
    display_name text not null,
    short_name text,

    location text,

    conference text,
    division text,

    logo_url text,

    active boolean not null default true,

    provider_data jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);


create unique index if not exists nhl_teams_abbreviation_unique
    on public.nhl_teams (
        upper(abbreviation)
    );


create index if not exists nhl_teams_active_idx
    on public.nhl_teams (
        active
    );


create index if not exists nhl_teams_conference_division_idx
    on public.nhl_teams (
        conference,
        division
    );


-- ============================================================
-- 2. NHL PLAYERS
-- ============================================================

create table if not exists public.nhl_players (
    id bigint generated by default as identity primary key,

    espn_athlete_id text unique,

    team_id bigint
        references public.nhl_teams(id)
        on delete set null,

    first_name text,
    last_name text,

    display_name text not null,
    short_name text,

    jersey_number text,

    position text,

    /*
     * Normalized G365 position group.
     *
     * Expected values:
     *   FORWARD
     *   DEFENSE
     *   GOALIE
     *
     * position retains the player's more specific position:
     *   C
     *   LW
     *   RW
     *   D
     *   G
     *
     * This allows NHL Season-Long leagues to support:
     *
     * Default:
     *   C / LW / RW / D / G
     *
     * Commissioner flexible mode:
     *   Forward / Defense / Goalie
     */
    position_group text,

    shoots_catches text,

    active boolean not null default true,

    status text,
    injury_status text,

    headshot_url text,

    provider_data jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint nhl_players_position_group_check
        check (
            position_group is null
            or position_group in (
                'FORWARD',
                'DEFENSE',
                'GOALIE'
            )
        )
);


create index if not exists nhl_players_team_id_idx
    on public.nhl_players (
        team_id
    );


create index if not exists nhl_players_position_idx
    on public.nhl_players (
        position
    );


create index if not exists nhl_players_position_group_idx
    on public.nhl_players (
        position_group
    );


create index if not exists nhl_players_active_idx
    on public.nhl_players (
        active
    );


create index if not exists nhl_players_team_active_idx
    on public.nhl_players (
        team_id,
        active
    );


-- ============================================================
-- 3. NHL GAMES
-- ============================================================

create table if not exists public.nhl_games (
    id bigint generated by default as identity primary key,

    espn_event_id text unique,

    season integer not null,

    /*
     * Normalized season stage.
     *
     * Expected values initially:
     *   preseason
     *   regular
     *   postseason
     *
     * Provider-specific values remain in provider_data.
     */
    season_type text not null default 'regular',

    game_date date,

    kickoff_at timestamptz not null,

    away_team_id bigint
        references public.nhl_teams(id)
        on delete restrict,

    home_team_id bigint
        references public.nhl_teams(id)
        on delete restrict,

    away_score integer not null default 0,
    home_score integer not null default 0,

    status_type text,
    status_name text,
    status_detail text,

    /*
     * NHL period:
     *   1
     *   2
     *   3
     *   overtime periods as supplied by provider
     */
    period integer,

    display_clock text,

    status_completed boolean not null default false,

    /*
     * Hockey-specific game state.
     */
    is_overtime boolean not null default false,
    is_shootout boolean not null default false,

    venue_name text,

    provider_data jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint nhl_games_different_teams_check
        check (
            home_team_id is null
            or away_team_id is null
            or home_team_id <> away_team_id
        )
);


create index if not exists nhl_games_season_idx
    on public.nhl_games (
        season
    );


create index if not exists nhl_games_season_type_idx
    on public.nhl_games (
        season,
        season_type
    );


create index if not exists nhl_games_kickoff_at_idx
    on public.nhl_games (
        kickoff_at
    );


create index if not exists nhl_games_home_team_idx
    on public.nhl_games (
        home_team_id
    );


create index if not exists nhl_games_away_team_idx
    on public.nhl_games (
        away_team_id
    );


create index if not exists nhl_games_status_completed_idx
    on public.nhl_games (
        status_completed
    );


create index if not exists nhl_games_live_lookup_idx
    on public.nhl_games (
        season,
        status_completed,
        kickoff_at
    );


