-- ============================================================
-- 10. FOUNDATION VERIFICATION
-- ============================================================

with expected_tables as (
    select *
    from (
        values
            ('nhl_teams'),
            ('nhl_players'),
            ('nhl_games'),
            ('nhl_player_game_stats'),
            ('nhl_team_game_stats')
    ) as x(table_name)
),

table_checks as (
    select
        e.table_name,

        exists (
            select 1
            from information_schema.tables t
            where t.table_schema = 'public'
              and t.table_name = e.table_name
        ) as table_exists,

        exists (
            select 1
            from pg_publication_tables p
            where p.pubname = 'supabase_realtime'
              and p.schemaname = 'public'
              and p.tablename = e.table_name
        ) as realtime_enabled

    from expected_tables e
)

select
    table_name,

    case
        when table_exists
        then 'PASS'
        else 'FAIL'
    end as table_result,

    case
        when realtime_enabled
        then 'PASS'
        else 'FAIL'
    end as realtime_result

from table_checks

order by
    table_name;