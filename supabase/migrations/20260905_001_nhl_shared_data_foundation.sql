-- ============================================================
-- 6. UPDATED_AT TRIGGER
--
-- NHL-specific function so we do not touch any shared/NFL
-- timestamp trigger behavior.
-- ============================================================

create or replace function private.touch_nhl_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public, private
as $$
begin
    new.updated_at := now();

    return new;
end;
$$;


drop trigger if exists trg_nhl_teams_updated_at
on public.nhl_teams;

create trigger trg_nhl_teams_updated_at
before update
on public.nhl_teams
for each row
execute function private.touch_nhl_updated_at();


drop trigger if exists trg_nhl_players_updated_at
on public.nhl_players;

