-- ============================================================
-- 11. INITIALIZATION FUNCTION
--
-- Creates settings + the four contest rounds.
-- Does NOT generate salaries yet.
-- ============================================================

create or replace function public.initialize_nfl_playoff_league(
    p_league_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_league public.leagues%rowtype;
    v_salary_cap numeric;
begin
    select *
    into v_league
    from public.leagues
    where id = p_league_id;

    if not found then
        raise exception 'League could not be found.';
    end if;

    if v_league.league_type <> 'nfl_playoffs' then
        raise exception 'League is not an NFL Playoffs league.';
    end if;

    if v_league.player_selection_mode = 'salary' then
        v_salary_cap := 65000;
    else
        v_salary_cap := null;
    end if;


    insert into public.nfl_playoff_settings (
        league_id,
        season,
        weekly_salary_cap
    )
    values (
        p_league_id,
        v_league.season,
        v_salary_cap
    )
    on conflict (league_id)
    do update set
        season = excluded.season,
        weekly_salary_cap =
            case
                when v_league.player_selection_mode = 'salary'
                    then coalesce(
                        public.nfl_playoff_settings.weekly_salary_cap,
                        excluded.weekly_salary_cap
                    )
                else null
            end,
        updated_at = now();


    insert into public.nfl_playoff_salary_settings (
        league_id
    )
    values (
        p_league_id
    )
    on conflict (league_id)
    do nothing;


    insert into public.nfl_playoff_league_state (
        league_id,
        season,
        active_round,
        status
    )
    values (
        p_league_id,
        v_league.season,
        1,
        'setup'
    )
    on conflict (league_id)
    do update set
        season = excluded.season,
        updated_at = now();


    insert into public.nfl_playoff_rounds (
        league_id,
        season,
        round_number,
        round_key,
        round_name
    )
    values
        (
            p_league_id,
            v_league.season,
            1,
            'wild_card',
            'Wild Card'
        ),
        (
            p_league_id,
            v_league.season,
            2,
            'divisional',
            'Divisional'
        ),
        (
            p_league_id,
            v_league.season,
            3,
            'conference',
            'Conference Championships'
        ),
        (
            p_league_id,
            v_league.season,
            4,
            'super_bowl',
            'Super Bowl'
        )
    on conflict (
        league_id,
        season,
        round_number
    )
    do update set
        round_key = excluded.round_key,
        round_name = excluded.round_name,
        updated_at = now();


    return jsonb_build_object(
        'success', true,
        'leagueId', p_league_id,
        'season', v_league.season,
        'playerSelectionMode',
            v_league.player_selection_mode,
        'rounds', 4,
        'salaryCap',
            v_salary_cap
    );
end;
$$;


-- ============================================================
-- 12. ROUND NAME HELPER
-- ============================================================

create or replace function public.get_nfl_playoff_round_name(
    p_round_number integer
)
returns text
language sql
immutable
as $$
    select
        case p_round_number
            when 1 then 'Wild Card'
            when 2 then 'Divisional'
            when 3 then 'Conference Championships'
            when 4 then 'Super Bowl'
            else 'Unknown'
        end;
$$;


-- ============================================================
-- 13. BASIC STANDINGS REBUILD
-- ============================================================

create or replace function public.rebuild_nfl_playoff_standings(
    p_league_id uuid,
    p_season integer
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_rows integer := 0;
begin

    insert into public.nfl_playoff_standings (
        league_id,
        fantasy_team_id,
        season,
        total_points,
        rounds_scored,
        highest_round_score,
        lowest_round_score,
        average_round_score,
        current_rank,
        updated_at
    )
    select
        s.league_id,
        s.fantasy_team_id,
        s.season,
        sum(s.fantasy_points),
        count(*) filter (
            where s.is_final
        ),
        max(s.fantasy_points),
        min(s.fantasy_points),
        case
            when count(*) > 0
                then avg(s.fantasy_points)
            else 0
        end,
        null,
        now()
    from public.nfl_playoff_round_scores s
    where s.league_id = p_league_id
      and s.season = p_season
    group by
        s.league_id,
        s.fantasy_team_id,
        s.season

    on conflict (
        league_id,
        fantasy_team_id,
        season
    )
    do update set
        total_points =
            excluded.total_points,

        rounds_scored =
            excluded.rounds_scored,

        highest_round_score =
            excluded.highest_round_score,

        lowest_round_score =
            excluded.lowest_round_score,

        average_round_score =
            excluded.average_round_score,

        updated_at =
            now();


    with ranked as (
        select
            id,
            row_number() over (
                order by
                    total_points desc,
                    highest_round_score desc,
                    fantasy_team_id asc
            ) as rank_number
        from public.nfl_playoff_standings
        where league_id = p_league_id
          and season = p_season
    )
    update public.nfl_playoff_standings s
    set
        current_rank =
            ranked.rank_number,
        updated_at =
            now()
    from ranked
    where s.id = ranked.id;


    get diagnostics
        v_rows =
            row_count;


    return jsonb_build_object(
        'success', true,
        'leagueId', p_league_id,
        'season', p_season,
        'standingsRows', v_rows
    );
end;
$$;


