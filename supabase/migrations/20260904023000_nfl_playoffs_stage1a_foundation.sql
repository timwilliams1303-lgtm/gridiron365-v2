-- ============================================================
-- G365 NFL PLAYOFFS
-- STAGE 1A — FOUNDATION
--
-- NFL Playoffs is a cumulative Total Points contest.
-- Salary / No-Salary is controlled by leagues.player_selection_mode.
-- Existing league_scoring_settings + league_scoring_rules remain
-- authoritative for fantasy scoring.
-- ============================================================


-- ============================================================
-- 1. NFL PLAYOFF LEAGUE SETTINGS
-- ============================================================

create table if not exists public.nfl_playoff_settings (
    id bigint generated by default as identity primary key,

    league_id uuid not null
        references public.leagues(id)
        on delete cascade,

    season integer not null,

    weekly_salary_cap numeric,

    starting_qb integer not null default 1,
    starting_rb integer not null default 2,
    starting_wr integer not null default 2,
    starting_te integer not null default 1,
    starting_flex integer not null default 2,
    starting_superflex integer not null default 0,
    starting_k integer not null default 1,
    starting_dst integer not null default 1,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint nfl_playoff_settings_league_unique
        unique (league_id),

    constraint nfl_playoff_settings_season_positive
        check (season >= 2000),

    constraint nfl_playoff_settings_salary_cap_positive
        check (
            weekly_salary_cap is null
            or weekly_salary_cap > 0
        ),

    constraint nfl_playoff_settings_lineup_nonnegative
        check (
            starting_qb >= 0
            and starting_rb >= 0
            and starting_wr >= 0
            and starting_te >= 0
            and starting_flex >= 0
            and starting_superflex >= 0
            and starting_k >= 0
            and starting_dst >= 0
        )
);


create index if not exists
    nfl_playoff_settings_league_idx
on public.nfl_playoff_settings (league_id);


-- ============================================================
-- 2. POSTSEASON ROUND STATE
--
-- round_number:
-- 1 = Wild Card
-- 2 = Divisional
-- 3 = Conference Championships
-- 4 = Super Bowl
--
-- nfl_week is intentionally nullable. We will map it from the
-- actual ESPN postseason schedule in Stage 1B rather than
-- hard-code provider week numbering here.
-- ============================================================

create table if not exists public.nfl_playoff_rounds (
    id bigint generated by default as identity primary key,

    league_id uuid not null
        references public.leagues(id)
        on delete cascade,

    season integer not null,

    round_number integer not null,

    round_key text not null,

    round_name text not null,

    nfl_week integer,

    status text not null default 'pending',

    opens_at timestamptz,
    first_kickoff_at timestamptz,
    last_scheduled_kickoff_at timestamptz,

    finalized_at timestamptz,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint nfl_playoff_rounds_unique
        unique (
            league_id,
            season,
            round_number
        ),

    constraint nfl_playoff_rounds_round_number_check
        check (
            round_number between 1 and 4
        ),

    constraint nfl_playoff_rounds_round_key_check
        check (
            round_key in (
                'wild_card',
                'divisional',
                'conference',
                'super_bowl'
            )
        ),

    constraint nfl_playoff_rounds_status_check
        check (
            status in (
                'pending',
                'open',
                'live',
                'finalizing',
                'final'
            )
        )
);


create index if not exists
    nfl_playoff_rounds_active_idx
on public.nfl_playoff_rounds (
    league_id,
    season,
    status
);


