-- ============================================================
-- 15. Commissioner settings. Picks required are configurable
--     from 1-20. Existing weeks keep their required_picks
--     snapshot; new weeks inherit the current league setting.
-- ============================================================

create or replace function public.save_pickem_settings(
  p_league_id uuid,
  p_football_scope text,
  p_picks_per_week integer,
  p_pick_lock_mode text,
  p_minimum_source_books integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_season integer;
begin
  if v_user is null then
    raise exception using errcode = '42501', message = 'You must be signed in.';
  end if;

  if not exists (
    select 1
    from public.league_members lm
    where lm.league_id = p_league_id
      and lm.user_id = v_user
      and lm.role in ('commissioner','co_commissioner')
  ) then
    raise exception using errcode = '42501', message = 'Commissioner access is required.';
  end if;

  select season into v_season
  from public.leagues
  where id = p_league_id
    and league_type = 'pickem';

  if not found then
    raise exception 'Pick''em league could not be found.';
  end if;

  if p_football_scope not in ('college_nfl','college_only','nfl_only') then
    raise exception using errcode = '22023', message = 'Invalid football scope.';
  end if;

  if p_picks_per_week not between 1 and 20 then
    raise exception using errcode = '22023', message = 'Picks required per week must be between 1 and 20.';
  end if;

  if p_pick_lock_mode not in ('per_game','full_card') then
    raise exception using errcode = '22023', message = 'Invalid pick lock mode.';
  end if;

  if p_minimum_source_books not between 1 and 20 then
    raise exception using errcode = '22023', message = 'Minimum sportsbook sources must be between 1 and 20.';
  end if;

  insert into public.pickem_settings (
    league_id,
    season,
    football_scope,
    picks_per_week,
    pick_lock_mode,
    minimum_source_books,
    updated_at
  ) values (
    p_league_id,
    v_season,
    p_football_scope,
    p_picks_per_week,
    p_pick_lock_mode,
    p_minimum_source_books,
    now()
  )
  on conflict (league_id)
  do update set
    football_scope = excluded.football_scope,
    picks_per_week = excluded.picks_per_week,
    pick_lock_mode = excluded.pick_lock_mode,
    minimum_source_books = excluded.minimum_source_books,
    updated_at = now();

  return jsonb_build_object(
    'success', true,
    'leagueId', p_league_id,
    'footballScope', p_football_scope,
    'picksPerWeek', p_picks_per_week,
    'pickLockMode', p_pick_lock_mode,
    'minimumSourceBooks', p_minimum_source_books
  );
end;
$$;

grant execute on function public.save_pickem_settings(uuid,text,integer,text,integer) to authenticated;


-- ============================================================
-- 16. Initialize a contest week and snapshot the current number
--     of required picks so future setting changes do not rewrite
--     a week already underway.
-- ============================================================

create or replace function public.initialize_pickem_week(
  p_league_id uuid,
  p_season integer,
  p_week integer,
  p_line_day_at timestamptz default null,
  p_finalize_not_before timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_required integer;
  v_week_id bigint;
begin
  if p_week not between 1 and 25 then
    raise exception using errcode = '22023', message = 'Pick''em week must be between 1 and 25.';
  end if;

  if v_user is not null and not exists (
    select 1 from public.league_members lm
    where lm.league_id = p_league_id
      and lm.user_id = v_user
      and lm.role in ('commissioner','co_commissioner')
  ) then
    raise exception using errcode = '42501', message = 'Commissioner access is required.';
  end if;

  select s.picks_per_week
  into v_required
  from public.pickem_settings s
  join public.leagues l on l.id = s.league_id
  where s.league_id = p_league_id
    and l.league_type = 'pickem'
    and l.season = p_season;

  if not found then
    raise exception 'Pick''em settings could not be found.';
  end if;

  insert into public.pickem_weeks (
    league_id, season, week, status, required_picks,
    line_day_at, finalize_not_before, updated_at
  ) values (
    p_league_id, p_season, p_week, 'setup', v_required,
    p_line_day_at, p_finalize_not_before, now()
  )
  on conflict (league_id, season, week)
  do update set
    line_day_at = coalesce(excluded.line_day_at, pickem_weeks.line_day_at),
    finalize_not_before = coalesce(excluded.finalize_not_before, pickem_weeks.finalize_not_before),
    updated_at = now()
  returning id into v_week_id;

  return jsonb_build_object(
    'success', true,
    'pickemWeekId', v_week_id,
    'requiredPicks', v_required
  );
end;
$$;

grant execute on function public.initialize_pickem_week(uuid,integer,integer,timestamptz,timestamptz) to authenticated;


-- ============================================================
-- 17. My-card status. A card is complete only when the exact
--     commissioner-configured number of picks exists.
-- ============================================================

create or replace function public.get_pickem_my_card_status(
  p_league_id uuid,
  p_season integer,
  p_week integer
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_team_id bigint;
  v_week_id bigint;
  v_required integer;
  v_selected integer := 0;
begin
  select ft.id
  into v_team_id
  from public.fantasy_teams ft
  where ft.league_id = p_league_id
    and ft.owner_id = v_user
    and coalesce(ft.active,true) = true
  order by ft.id
  limit 1;

  if not found then
    raise exception using errcode = '42501', message = 'A Pick''em entry could not be found for this member.';
  end if;

  select w.id, w.required_picks
  into v_week_id, v_required
  from public.pickem_weeks w
  where w.league_id = p_league_id
    and w.season = p_season
    and w.week = p_week;

  if not found then
    return jsonb_build_object(
      'success', true,
      'weekReady', false,
      'selectedPicks', 0,
      'requiredPicks', coalesce((select picks_per_week from public.pickem_settings where league_id = p_league_id), 5),
      'isComplete', false
    );
  end if;

  select count(*)::integer
  into v_selected
  from public.pickem_picks p
  where p.pickem_week_id = v_week_id
    and p.fantasy_team_id = v_team_id
    and p.result <> 'void';

  return jsonb_build_object(
    'success', true,
    'weekReady', true,
    'pickemWeekId', v_week_id,
    'selectedPicks', v_selected,
    'requiredPicks', v_required,
    'remainingPicks', greatest(v_required - v_selected, 0),
    'isComplete', v_selected = v_required
  );
end;
$$;

grant execute on function public.get_pickem_my_card_status(uuid,integer,integer) to authenticated;


-- ============================================================
-- 18. Save one ATS pick. The database enforces:
--     - only the entry owner
--     - exact weekly maximum
--     - frozen official G365 spread
--     - per-game kickoff lock
--     - optional full-card lock
-- ============================================================

create or replace function public.save_pickem_pick(
  p_league_id uuid,
  p_season integer,
  p_week integer,
  p_pickem_game_id bigint,
  p_selected_side text
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_team_id bigint;
  v_week public.pickem_weeks%rowtype;
  v_game public.pickem_games%rowtype;
  v_lock_mode text;
  v_count integer := 0;
  v_existing_id bigint;
  v_earliest_selected_kickoff timestamptz;
begin
  if p_selected_side not in ('home','away') then
    raise exception using errcode = '22023', message = 'Pick side must be home or away.';
  end if;

  select ft.id
  into v_team_id
  from public.fantasy_teams ft
  where ft.league_id = p_league_id
    and ft.owner_id = v_user
    and coalesce(ft.active,true) = true
  order by ft.id
  limit 1;

  if not found then
    raise exception using errcode = '42501', message = 'You do not own an active entry in this Pick''em league.';
  end if;

  select * into v_week
  from public.pickem_weeks
  where league_id = p_league_id
    and season = p_season
    and week = p_week
  for update;

  if not found then
    raise exception 'Pick''em week has not been initialized.';
  end if;

  if v_week.status = 'final' then
    raise exception using errcode = '22023', message = 'This Pick''em week is already final.';
  end if;

  select * into v_game
  from public.pickem_games
  where id = p_pickem_game_id
    and league_id = p_league_id
    and pickem_week_id = v_week.id
  for update;

  if not found then
    raise exception 'Selected Pick''em game could not be found on this week''s card.';
  end if;

  if not v_game.is_eligible or v_game.spread_status <> 'frozen' or v_game.g365_home_spread is null then
    raise exception using errcode = '22023', message = 'This game does not have an eligible frozen G365 Spread.';
  end if;

  if now() >= v_game.kickoff_at or v_game.is_started or v_game.is_final then
    raise exception using errcode = '22023', message = 'This game has kicked off and the pick is locked.';
  end if;

  select s.pick_lock_mode
  into v_lock_mode
  from public.pickem_settings s
  where s.league_id = p_league_id;

  if v_lock_mode = 'full_card' then
    select min(g.kickoff_at)
    into v_earliest_selected_kickoff
    from public.pickem_picks p
    join public.pickem_games g on g.id = p.pickem_game_id
    where p.pickem_week_id = v_week.id
      and p.fantasy_team_id = v_team_id
      and p.result <> 'void';

    if v_earliest_selected_kickoff is not null and now() >= v_earliest_selected_kickoff then
      raise exception using errcode = '22023', message = 'Your full Pick''em card is locked.';
    end if;
  end if;

  select id into v_existing_id
  from public.pickem_picks
  where pickem_week_id = v_week.id
    and fantasy_team_id = v_team_id
    and pickem_game_id = v_game.id;

  if v_existing_id is null then
    select count(*)::integer into v_count
    from public.pickem_picks
    where pickem_week_id = v_week.id
      and fantasy_team_id = v_team_id
      and result <> 'void';

    if v_count >= v_week.required_picks then
      raise exception using errcode = '22023', message = format('You may select exactly %s games this week.', v_week.required_picks);
    end if;

    insert into public.pickem_picks (
      league_id,
      pickem_week_id,
      fantasy_team_id,
      pickem_game_id,
      selected_side,
      frozen_home_spread,
      submitted_at,
      updated_at
    ) values (
      p_league_id,
      v_week.id,
      v_team_id,
      v_game.id,
      p_selected_side,
      v_game.g365_home_spread,
      now(),
      now()
    );
  else
    update public.pickem_picks
    set selected_side = p_selected_side,
        frozen_home_spread = v_game.g365_home_spread,
        updated_at = now()
    where id = v_existing_id;
  end if;

  select count(*)::integer into v_count
  from public.pickem_picks
  where pickem_week_id = v_week.id
    and fantasy_team_id = v_team_id
    and result <> 'void';

  return jsonb_build_object(
    'success', true,
    'selectedPicks', v_count,
    'requiredPicks', v_week.required_picks,
    'remainingPicks', greatest(v_week.required_picks - v_count, 0),
    'isComplete', v_count = v_week.required_picks
  );
end;
$$;

grant execute on function public.save_pickem_pick(uuid,integer,integer,bigint,text) to authenticated;


