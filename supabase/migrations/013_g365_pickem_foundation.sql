-- ============================================================
-- 1. Allow the new league type/mode without changing existing
--    Traditional / Season-Long / NFL Playoffs behavior.
-- ============================================================

do $$
declare
  r record;
begin
  for r in
    select conname
    from pg_constraint
    where conrelid = 'public.leagues'::regclass
      and contype = 'c'
      and (
        pg_get_constraintdef(oid) ilike '%league_type%'
        or pg_get_constraintdef(oid) ilike '%player_selection_mode%'
      )
  loop
    execute format('alter table public.leagues drop constraint %I', r.conname);
  end loop;
end
$$;

alter table public.leagues
  add constraint leagues_league_type_g365_check
  check (league_type in ('traditional','season_long','nfl_playoffs','pickem'));

alter table public.leagues
