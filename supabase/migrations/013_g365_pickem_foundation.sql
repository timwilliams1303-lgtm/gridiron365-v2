-- ============================================================
-- 9. Create a Pick'em league without modifying the existing
--    create_league_transaction used by the other league types.
-- ============================================================

create or replace function public.create_pickem_league_transaction(
  p_name text,
  p_season integer,
  p_entry_name text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_league_id uuid;
  v_team_id bigint;
  v_name text := trim(coalesce(p_name, ''));
  v_entry_name text := trim(coalesce(p_entry_name, ''));
begin
  if v_user_id is null then
    raise exception using errcode = '42501', message = 'You must be signed in to create a league.';
  end if;

  if length(v_name) not between 1 and 100 then
    raise exception using errcode = '22023', message = 'League name must be between 1 and 100 characters.';
  end if;

  if length(v_entry_name) not between 1 and 100 then
    raise exception using errcode = '22023', message = 'A Pick''em league requires an entry name between 1 and 100 characters.';
  end if;

  if p_season is null or p_season not between 2000 and 2200 then
    raise exception using errcode = '22023', message = 'A valid league season is required.';
  end if;

  insert into public.leagues (
    name, league_type, season, commissioner_user_id, status, player_selection_mode
  ) values (
    v_name, 'pickem', p_season, v_user_id, 'setup', 'pickem'
  ) returning id into v_league_id;

  insert into public.league_members (league_id, user_id, role)
  values (v_league_id, v_user_id, 'commissioner');

  -- Keep the shared league shell/settings expectations intact.
  insert into public.league_settings (league_id, season, max_teams, regular_season_weeks)
  values (v_league_id, p_season, null, null);

  insert into public.fantasy_teams (league_id, owner_id, team_name, active)
  values (v_league_id, v_user_id, v_entry_name, true)
  returning id into v_team_id;

  insert into public.pickem_settings (league_id, season)
  values (v_league_id, p_season);

  return jsonb_build_object(
    'success', true,
    'leagueId', v_league_id,
    'leagueType', 'pickem',
    'playerSelectionMode', 'pickem',
    'season', p_season,
    'role', 'commissioner',
    'fantasyTeamId', v_team_id
  );
end;
$$;

revoke all on function public.create_pickem_league_transaction(text,integer,text) from public;
grant execute on function public.create_pickem_league_transaction(text,integer,text) to authenticated;

-- ============================================================
-- 10. Freeze consensus spread as MEDIAN of the latest captured
--     line from each sportsbook. This is provider-neutral.
-- ============================================================

create or replace function public.freeze_pickem_g365_spread(
  p_pickem_game_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_league_id uuid;
  v_min_books integer;
  v_count integer;
  v_median numeric(6,2);
  v_user uuid := auth.uid();
begin
  select g.league_id, s.minimum_source_books
  into v_league_id, v_min_books
  from public.pickem_games g
  join public.pickem_settings s on s.league_id = g.league_id
  where g.id = p_pickem_game_id
  for update of g;

  if not found then
    raise exception 'Pick''em game could not be found.';
  end if;

  if v_user is not null and not exists (
    select 1 from public.league_members lm
    where lm.league_id = v_league_id
      and lm.user_id = v_user
      and lm.role in ('commissioner','co_commissioner')
  ) then
    raise exception using errcode = '42501', message = 'Commissioner access is required.';
  end if;

  with latest as (
    select distinct on (sportsbook_key)
      sportsbook_key, home_spread
    from public.pickem_line_sources
    where pickem_game_id = p_pickem_game_id
    order by sportsbook_key, captured_at desc, id desc
  )
  select count(*), percentile_cont(0.5) within group (order by home_spread)::numeric(6,2)
  into v_count, v_median
  from latest;

  if v_count < v_min_books then
    update public.pickem_games
    set spread_status = 'excluded',
        is_eligible = false,
        exclusion_reason = format('Only %s trustworthy source lines were available; %s required.', v_count, v_min_books),
        consensus_source_count = v_count,
        updated_at = now()
    where id = p_pickem_game_id;

    return jsonb_build_object('success', false, 'excluded', true, 'sourceCount', v_count);
  end if;

  update public.pickem_games
  set g365_home_spread = v_median,
      spread_status = 'frozen',
      spread_published_at = coalesce(spread_published_at, now()),
      spread_frozen_at = now(),
      consensus_source_count = v_count,
      consensus_method = 'median_latest_per_sportsbook',
      is_eligible = true,
      exclusion_reason = null,
      updated_at = now()
  where id = p_pickem_game_id;

  return jsonb_build_object(
    'success', true,
    'gameId', p_pickem_game_id,
    'g365HomeSpread', v_median,
    'sourceCount', v_count,
    'method', 'median_latest_per_sportsbook'
  );
end;
$$;

grant execute on function public.freeze_pickem_g365_spread(bigint) to authenticated;

-- ============================================================
-- 11. Pick grading using frozen G365 spread only.
-- ============================================================

create or replace function public.grade_pickem_game(p_pickem_game_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_game public.pickem_games%rowtype;
  v_settings public.pickem_settings%rowtype;
  v_home_ats numeric;
  v_rows integer := 0;
begin
  select * into v_game
  from public.pickem_games
  where id = p_pickem_game_id
  for update;

  if not found then
    raise exception 'Pick''em game could not be found.';
  end if;

  if not v_game.is_final then
    return jsonb_build_object('success', true, 'graded', false, 'reason', 'game_not_final');
  end if;

  if v_game.g365_home_spread is null then
    return jsonb_build_object('success', true, 'graded', false, 'reason', 'no_frozen_spread');
  end if;

  select * into v_settings from public.pickem_settings where league_id = v_game.league_id;
  v_home_ats := coalesce(v_game.home_score,0) + v_game.g365_home_spread - coalesce(v_game.away_score,0);

  update public.pickem_picks p
  set result = case
        when v_home_ats = 0 then 'push'
        when p.selected_side = 'home' and v_home_ats > 0 then 'win'
        when p.selected_side = 'away' and v_home_ats < 0 then 'win'
        else 'loss'
      end,
      points_awarded = case
        when v_home_ats = 0 then v_settings.push_points
        when p.selected_side = 'home' and v_home_ats > 0 then v_settings.win_points
        when p.selected_side = 'away' and v_home_ats < 0 then v_settings.win_points
        else v_settings.loss_points
      end,
      locked_at = coalesce(p.locked_at, v_game.kickoff_at),
      graded_at = now(),
      updated_at = now()
  where p.pickem_game_id = p_pickem_game_id
    and p.result <> 'void';

  get diagnostics v_rows = row_count;
  return jsonb_build_object('success', true, 'graded', true, 'picksGraded', v_rows);
end;
$$;

-- ============================================================
-- 12. Refresh weekly live record; finalization remains separate.
-- ============================================================

create or replace function public.refresh_pickem_week_results(p_pickem_week_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_week public.pickem_weeks%rowtype;
  v_rows integer := 0;
begin
  select * into v_week from public.pickem_weeks where id = p_pickem_week_id;
  if not found then raise exception 'Pick''em week could not be found.'; end if;

  insert into public.pickem_weekly_results (
    league_id, pickem_week_id, fantasy_team_id, wins, losses, pushes, pending, points, is_final, updated_at
  )
  select
    v_week.league_id,
    v_week.id,
    ft.id,
    count(p.id) filter (where p.result = 'win')::integer,
    count(p.id) filter (where p.result = 'loss')::integer,
    count(p.id) filter (where p.result = 'push')::integer,
    count(p.id) filter (where p.result = 'pending')::integer,
    coalesce(sum(p.points_awarded),0),
    false,
    now()
  from public.fantasy_teams ft
  left join public.pickem_picks p
    on p.fantasy_team_id = ft.id
   and p.pickem_week_id = v_week.id
  where ft.league_id = v_week.league_id
    and coalesce(ft.active,true) = true
  group by ft.id
  on conflict (pickem_week_id, fantasy_team_id)
  do update set
    wins = excluded.wins,
    losses = excluded.losses,
    pushes = excluded.pushes,
    pending = excluded.pending,
    points = excluded.points,
    updated_at = now();

  get diagnostics v_rows = row_count;
  return jsonb_build_object('success', true, 'rows', v_rows);
end;
$$;

-- ============================================================
-- 13. Finalize only AFTER Monday-night gate AND every eligible
--     game on the card is actually final.
-- ============================================================

create or replace function public.finalize_pickem_week(p_pickem_week_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_week public.pickem_weeks%rowtype;
  v_unfinished integer;
  v_user uuid := auth.uid();
begin
  select * into v_week
  from public.pickem_weeks
  where id = p_pickem_week_id
  for update;

  if not found then raise exception 'Pick''em week could not be found.'; end if;

  if v_week.status = 'final' then
    return jsonb_build_object('success', true, 'finalized', true, 'alreadyFinal', true);
  end if;

  if v_week.finalize_not_before is not null and now() < v_week.finalize_not_before then
    return jsonb_build_object('success', true, 'finalized', false, 'reason', 'monday_night_gate_not_reached');
  end if;

  select count(*) into v_unfinished
  from public.pickem_games
  where pickem_week_id = v_week.id
    and is_eligible = true
    and is_final = false;

  if v_unfinished > 0 then
    update public.pickem_weeks
      set status = 'awaiting_finalization', updated_at = now()
    where id = v_week.id;

    return jsonb_build_object('success', true, 'finalized', false, 'reason', 'games_still_unfinished', 'unfinishedGames', v_unfinished);
  end if;

  perform public.refresh_pickem_week_results(v_week.id);

  with ranked as (
    select id,
           dense_rank() over (order by points desc, wins desc, losses asc) as rnk
    from public.pickem_weekly_results
    where pickem_week_id = v_week.id
  )
  update public.pickem_weekly_results r
  set is_final = true,
      weekly_rank = ranked.rnk,
      finalized_at = now(),
      updated_at = now()
  from ranked
  where r.id = ranked.id;

  update public.pickem_weeks
  set status = 'final',
      finalized_at = now(),
      finalized_by = v_user,
      updated_at = now()
  where id = v_week.id;

  return jsonb_build_object('success', true, 'finalized', true, 'week', v_week.week);
end;
$$;

-- ============================================================
-- 14. Safe member-facing league picks view.
-- This prevents pre-kickoff leakage from direct client queries.
-- ============================================================

create or replace function public.get_pickem_league_picks(
  p_league_id uuid,
  p_season integer,
  p_week integer
)
returns table (
  fantasy_team_id bigint,
  team_name text,
  pick_id bigint,
  game_id bigint,
  sport text,
  kickoff_at timestamptz,
  away_team_name text,
  home_team_name text,
  away_score integer,
  home_score integer,
  status_type text,
  status_name text,
  status_detail text,
  period integer,
  display_clock text,
  is_final boolean,
  pick_visible boolean,
  selected_side text,
  frozen_home_spread numeric,
  pick_result text,
  points_awarded numeric
)
language sql
stable
security definer
set search_path = public, auth
as $$
  with me as (
    select auth.uid() as user_id
  ), rows as (
    select
      ft.id as fantasy_team_id,
      ft.team_name,
      ft.owner_id,
      p.id as pick_id,
      g.id as game_id,
      g.sport,
      g.kickoff_at,
      g.away_team_name,
      g.home_team_name,
      g.away_score,
      g.home_score,
      g.status_type,
      g.status_name,
      g.status_detail,
      g.period,
      g.display_clock,
      g.is_final,
      p.selected_side,
      p.frozen_home_spread,
      p.result as pick_result,
      p.points_awarded,
      (ft.owner_id = me.user_id or now() >= g.kickoff_at or g.is_started or g.is_final) as visible
    from public.fantasy_teams ft
    cross join me
    join public.league_members lm
      on lm.league_id = p_league_id
     and lm.user_id = me.user_id
    left join public.pickem_weeks w
      on w.league_id = p_league_id
     and w.season = p_season
     and w.week = p_week
    left join public.pickem_picks p
      on p.pickem_week_id = w.id
     and p.fantasy_team_id = ft.id
    left join public.pickem_games g
      on g.id = p.pickem_game_id
    where ft.league_id = p_league_id
      and coalesce(ft.active,true) = true
  )
  select
    fantasy_team_id,
    team_name,
    pick_id,
    case when visible then game_id else null end,
    case when visible then sport else null end,
    case when visible then kickoff_at else null end,
    case when visible then away_team_name else null end,
    case when visible then home_team_name else null end,
    case when visible then away_score else null end,
    case when visible then home_score else null end,
    case when visible then status_type else null end,
    case when visible then status_name else null end,
    case when visible then status_detail else null end,
    case when visible then period else null end,
    case when visible then display_clock else null end,
    case when visible then is_final else false end,
    coalesce(visible, false),
    case when visible then selected_side else null end,
    case when visible then frozen_home_spread else null end,
    case when visible then pick_result else null end,
    case when visible then points_awarded else null end
  from rows
  order by team_name,
           case when visible then kickoff_at else null end nulls last,
           pick_id;
$$;

