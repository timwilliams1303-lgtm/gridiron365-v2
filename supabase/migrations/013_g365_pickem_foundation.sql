  exists (
    select 1
    from public.fantasy_teams ft
    join public.pickem_games g on g.id = pickem_picks.pickem_game_id
    where ft.id = pickem_picks.fantasy_team_id
      and ft.owner_id = auth.uid()
      and ft.league_id = pickem_picks.league_id
      and g.league_id = pickem_picks.league_id
      and g.is_eligible = true
      and g.spread_status = 'frozen'
      and now() < g.kickoff_at
  )
);

drop policy if exists pickem_picks_owner_update on public.pickem_picks;

create policy pickem_picks_owner_update on public.pickem_picks
