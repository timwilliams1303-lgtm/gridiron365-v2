-- ---------------------------------------------------------------------------

create or replace function public.get_nhl_pickem_league_picks(
  p_league_id uuid,
  p_season integer,
  p_period_number integer
)
returns table (
  entry_id bigint,
  fantasy_team_id bigint,
  entry_name text,
  user_id uuid,
  pick_id bigint,
  nhl_pickem_game_id bigint,
  nhl_game_id bigint,
  market_type text,
  selected_side text,
  snapshot_home_puck_line numeric,
  snapshot_away_puck_line numeric,
  snapshot_total numeric,
  confidence_value numeric,
  locked_at timestamptz,
  result text,
  points_awarded numeric,
  kickoff_at timestamptz,
  home_team_id bigint,
  away_team_id bigint,
  home_score integer,
  away_score integer,
  game_status text,
  period integer,
  display_clock text,
  is_own_entry boolean
)
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_period_id bigint;
begin
  if v_user_id is null then
    raise exception 'Authentication is required.';
  end if;

  if not private.is_league_member(p_league_id, v_user_id) then
    raise exception 'You are not a member of this NHL Pick''em league.';
  end if;

  select p.id into v_period_id
  from public.nhl_pickem_periods p
  where p.league_id = p_league_id
    and p.season = p_season
    and p.period_number = p_period_number;

  if v_period_id is null then
    raise exception 'NHL Pick''em period could not be found.';
  end if;

  return query
  select
    e.id,
    e.fantasy_team_id,
    e.entry_name,
    e.user_id,
    pk.id,
    pg.id,
    ng.id,
    pk.market_type,
    pk.selected_side,
    pk.snapshot_home_puck_line,
    pk.snapshot_away_puck_line,
    pk.snapshot_total,
    pk.confidence_value,
    pk.locked_at,
    pk.result,
    pk.points_awarded,
    ng.kickoff_at,
    ng.home_team_id,
    ng.away_team_id,
    ng.home_score,
    ng.away_score,
    ng.status_name,
    ng.period,
    ng.display_clock,
    (e.user_id = v_user_id)
  from public.nhl_pickem_entries e
  join public.nhl_pickem_picks pk
    on pk.entry_id = e.id
   and pk.nhl_pickem_period_id = v_period_id
  join public.nhl_pickem_games pg
    on pg.id = pk.nhl_pickem_game_id
  join public.nhl_games ng
    on ng.id = pg.nhl_game_id
  where e.league_id = p_league_id
    and e.season = p_season
    and e.active = true
    and (
      e.user_id = v_user_id
      or pk.locked_at is not null
      or now() >= ng.kickoff_at
    )
  order by e.entry_name, ng.kickoff_at, pk.id;
end;
$$;

-- ---------------------------------------------------------------------------
-- Build persistent awards for one finalized period.
-- ---------------------------------------------------------------------------

create or replace function public.build_nhl_pickem_period_awards(
  p_nhl_pickem_period_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_period public.nhl_pickem_periods%rowtype;
  v_history_id uuid;
  v_inserted integer := 0;
begin
  select * into v_period
  from public.nhl_pickem_periods
  where id = p_nhl_pickem_period_id;

  if not found then
    raise exception 'NHL Pick''em period could not be found.';
  end if;

  if v_period.status <> 'final' then
    return jsonb_build_object(
      'success', true,
      'periodId', v_period.id,
      'awardsCreated', 0,
      'reason', 'period_not_final'
    );
  end if;

  select nhl_pickem_history_id into v_history_id
  from public.leagues
  where id = v_period.league_id;

  if v_history_id is null then
    v_history_id := public.ensure_nhl_pickem_history_identity(v_period.league_id);
  end if;

  -- Period winner(s), including legitimate ties.
  with inserted as (
    insert into public.nhl_pickem_awards (
      history_id,
      franchise_id,
      league_id,
      season,
      nhl_pickem_period_id,
      award_type,
      award_key,
      title,
      description,
      metadata
    )
    select
      v_history_id,
      e.franchise_id,
      v_period.league_id,
      v_period.season,
      v_period.id,
      'period_winner',
      format('period_%s_winner', v_period.period_number),
      format('Period %s Winner', v_period.period_number),
      format(
        '%s finished first in G365 NHL Pick''em Period %s.',
        e.entry_name,
        v_period.period_number
      ),
      jsonb_build_object(
        'periodNumber', v_period.period_number,
        'wins', r.wins,
        'pushes', r.pushes,
        'losses', r.losses,
        'points', r.points
      )
    from public.nhl_pickem_period_results r
    join public.nhl_pickem_entries e on e.id = r.entry_id
    where r.nhl_pickem_period_id = v_period.id
      and r.is_period_winner = true
      and e.franchise_id is not null
    on conflict (league_id, season, award_key, franchise_id) do nothing
    returning id
  )
  select count(*) into v_inserted from inserted;

  return jsonb_build_object(
    'success', true,
    'periodId', v_period.id,
    'awardsCreated', v_inserted
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Season awards/champion. Safe to rerun.
-- ---------------------------------------------------------------------------

create or replace function public.build_nhl_pickem_season_awards(
  p_league_id uuid,
  p_season integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_history_id uuid;
  v_unfinalized integer := 0;
  v_inserted integer := 0;
begin
