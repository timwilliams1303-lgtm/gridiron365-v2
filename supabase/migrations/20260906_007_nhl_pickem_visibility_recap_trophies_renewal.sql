-- ---------------------------------------------------------------------------
-- Recap payload.
-- ---------------------------------------------------------------------------

create or replace function public.get_nhl_pickem_recap(
  p_league_id uuid,
  p_season integer,
  p_period_number integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_period_id bigint;
  v_period_json jsonb := null;
  v_results jsonb := '[]'::jsonb;
  v_standings jsonb := '[]'::jsonb;
  v_awards jsonb := '[]'::jsonb;
begin
  if v_user_id is null
     or not private.is_league_member(p_league_id, v_user_id)
  then
    raise exception 'You are not a member of this NHL Pick''em league.';
  end if;

  if p_period_number is not null then
    select p.id,
           jsonb_build_object(
             'id', p.id,
             'periodNumber', p.period_number,
             'startsAt', p.starts_at,
             'endsAt', p.ends_at,
             'status', p.status,
             'finalizedAt', p.finalized_at
           )
      into v_period_id, v_period_json
    from public.nhl_pickem_periods p
    where p.league_id = p_league_id
      and p.season = p_season
      and p.period_number = p_period_number;

    select coalesce(jsonb_agg(x.obj order by x.rank, x.entry_name), '[]'::jsonb)
      into v_results
    from (
      select
        r.rank,
        e.entry_name,
        jsonb_build_object(
          'entryId', e.id,
          'entryName', e.entry_name,
          'rank', r.rank,
          'winner', r.is_period_winner,
          'requiredPicks', r.required_picks,
          'submittedPicks', r.submitted_picks,
          'missingPicks', r.missing_picks,
          'wins', r.wins,
          'pushes', r.pushes,
          'losses', r.losses,
          'ungraded', r.ungraded,
          'points', r.points
        ) as obj
      from public.nhl_pickem_period_results r
      join public.nhl_pickem_entries e on e.id = r.entry_id
      where r.nhl_pickem_period_id = v_period_id
    ) x;
  end if;

  select coalesce(jsonb_agg(x.obj order by x.rank, x.entry_name), '[]'::jsonb)
    into v_standings
  from (
    select
      s.rank,
      e.entry_name,
      jsonb_build_object(
        'entryId', e.id,
        'entryName', e.entry_name,
        'rank', s.rank,
        'wins', s.wins,
        'pushes', s.pushes,
        'losses', s.losses,
        'ungraded', s.ungraded,
        'points', s.points
      ) as obj
    from public.nhl_pickem_standings s
    join public.nhl_pickem_entries e on e.id = s.entry_id
    where s.league_id = p_league_id
      and s.season = p_season
  ) x;

  select coalesce(jsonb_agg(
    jsonb_build_object(
      'awardType', a.award_type,
      'awardKey', a.award_key,
      'title', a.title,
      'description', a.description,
      'entryName', e.entry_name,
      'awardedAt', a.awarded_at,
      'metadata', a.metadata
    )
    order by a.awarded_at desc, a.id desc
  ), '[]'::jsonb)
  into v_awards
  from public.nhl_pickem_awards a
  left join public.nhl_pickem_franchises f on f.id = a.franchise_id
  left join public.nhl_pickem_entries e
    on e.franchise_id = f.id
   and e.league_id = p_league_id
   and e.season = p_season
  where a.league_id = p_league_id
    and a.season = p_season
    and (
      p_period_number is null
      or a.nhl_pickem_period_id = v_period_id
      or a.nhl_pickem_period_id is null
    );

  return jsonb_build_object(
    'success', true,
    'leagueId', p_league_id,
    'season', p_season,
    'period', v_period_json,
    'periodResults', v_results,
    'standings', v_standings,
    'awards', v_awards
  );
end;
$$;

