-- ---------------------------------------------------------------------------
-- Renewal.
--
-- Creates the next-season league while preserving NHL Pick'em history and
-- franchise identity. Every active owner receives membership, a new season
-- fantasy team, entry, and standings row. Commissioner settings carry forward.
-- Period dates are generated separately once the new NHL schedule anchor is
-- known, avoiding guessed future season dates.
-- ---------------------------------------------------------------------------

create or replace function public.renew_nhl_pickem_league(
  p_league_id uuid,
  p_new_season integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_old public.leagues%rowtype;
  v_new_league_id uuid;
  v_history_id uuid;
  v_settings public.nhl_pickem_settings%rowtype;
  r record;
  v_new_team_id bigint;
  v_new_entry_id bigint;
  v_members integer := 0;
begin
  perform private.assert_nhl_pickem_commissioner(p_league_id, v_user_id);

  select * into v_old
  from public.leagues
  where id = p_league_id
  for update;

  if p_new_season is null or p_new_season <= v_old.season then
    raise exception 'Renewal season must be later than the current season.';
  end if;

  v_history_id := public.ensure_nhl_pickem_history_identity(p_league_id);

  if exists (
    select 1
    from public.leagues
    where nhl_pickem_history_id = v_history_id
      and season = p_new_season
  ) then
    raise exception 'This NHL Pick''em history already has a league for season %.', p_new_season;
  end if;

  select * into v_settings
  from public.nhl_pickem_settings
  where league_id = p_league_id;

  insert into public.leagues (
    name,
    league_type,
    season,
    commissioner_user_id,
    status,
    player_selection_mode,
    nhl_pickem_history_id
  )
  values (
    v_old.name,
    'nhl_pickem',
    p_new_season,
    v_old.commissioner_user_id,
    'setup',
    v_old.player_selection_mode,
    v_history_id
  )
  returning id into v_new_league_id;

  insert into public.nhl_pickem_settings (
    league_id,
    picks_per_period,
    market_mode,
    allow_same_game_multiple_markets,
    pick_lock_mode,
    minimum_source_books,
    scoring_mode,
    win_points,
    push_points,
    loss_points,
    confidence_points,
    confidence_push_multiplier,
    missing_pick_policy,
    contest_timezone,
    line_freeze_local_time
  )
  values (
    v_new_league_id,
    v_settings.picks_per_period,
    v_settings.market_mode,
    v_settings.allow_same_game_multiple_markets,
    'game',
    v_settings.minimum_source_books,
    v_settings.scoring_mode,
    v_settings.win_points,
    v_settings.push_points,
    v_settings.loss_points,
    v_settings.confidence_points,
    v_settings.confidence_push_multiplier,
    v_settings.missing_pick_policy,
    'America/New_York',
    time '11:00:00'
  );

  for r in
    select
      e.user_id,
      e.entry_name,
      e.franchise_id,
      case
        when e.user_id = v_old.commissioner_user_id then 'commissioner'
        else 'member'
      end as member_role
    from public.nhl_pickem_entries e
    where e.league_id = p_league_id
      and e.season = v_old.season
      and e.active = true
      and e.user_id is not null
      and e.franchise_id is not null
  loop
    insert into public.league_members(league_id, user_id, role)
    values(v_new_league_id, r.user_id, r.member_role)
    on conflict do nothing;

    update public.nhl_pickem_franchises
    set owner_id = r.user_id,
        display_name = r.entry_name,
        active = true,
        updated_at = now()
    where id = r.franchise_id;

    insert into public.fantasy_teams (
      league_id,
      owner_id,
      team_name,
      active,
      is_cpu,
      nhl_pickem_franchise_id
    )
    values (
      v_new_league_id,
      r.user_id,
      r.entry_name,
      true,
      false,
      r.franchise_id
    )
    returning id into v_new_team_id;

    insert into public.nhl_pickem_entries (
      league_id,
      fantasy_team_id,
      user_id,
      franchise_id,
      season,
      entry_name,
      active
    )
    values (
      v_new_league_id,
      v_new_team_id,
      r.user_id,
      r.franchise_id,
      p_new_season,
      r.entry_name,
      true
    )
    returning id into v_new_entry_id;

    insert into public.nhl_pickem_standings (
      league_id,
      season,
      entry_id,
      fantasy_team_id
    )
    values (
      v_new_league_id,
      p_new_season,
      v_new_entry_id,
      v_new_team_id
    );

    v_members := v_members + 1;
  end loop;

  return jsonb_build_object(
    'success', true,
    'oldLeagueId', p_league_id,
    'newLeagueId', v_new_league_id,
    'oldSeason', v_old.season,
    'newSeason', p_new_season,
    'historyId', v_history_id,
    'membersRenewed', v_members
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Extend lifecycle so period awards and season championship history are created
-- automatically after finalization.
-- ---------------------------------------------------------------------------

create or replace function public.advance_nhl_pickem_period_lifecycle()
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  r record;
  v_result jsonb;
  v_finalized integer := 0;
  v_waiting integer := 0;
  v_awards integer := 0;
  v_locked jsonb;
  v_graded jsonb;
begin
  v_locked := public.lock_due_nhl_pickem_picks();
  v_graded := public.grade_final_nhl_pickem_games(1000);

  update public.nhl_pickem_periods
  set status = case
        when status = 'final' then 'final'
        when now() < starts_at then 'upcoming'
        when now() < ends_at then 'open'
        else 'locked'
      end,
      updated_at = now()
  where status <> 'final';

  for r in
    select p.id, p.league_id, p.season
    from public.nhl_pickem_periods p
    join public.leagues l on l.id = p.league_id
    where l.league_type = 'nhl_pickem'
      and p.status <> 'final'
      and now() >= p.ends_at
    order by p.ends_at, p.id
  loop
    v_result := public.finalize_nhl_pickem_period(r.id);

    if coalesce((v_result ->> 'finalized')::boolean, false) then
      v_finalized := v_finalized + 1;
      v_result := public.build_nhl_pickem_period_awards(r.id);
      v_awards := v_awards + coalesce((v_result ->> 'awardsCreated')::integer,0);
      perform public.build_nhl_pickem_season_awards(r.league_id, r.season);
    else
      v_waiting := v_waiting + 1;
    end if;
  end loop;

  return jsonb_build_object(
    'success', true,
    'lockedPicks', coalesce((v_locked ->> 'lockedPicks')::integer,0),
    'gamesGraded', coalesce((v_graded ->> 'gamesGraded')::integer,0),
