    into v_history_id
  from public.leagues
  where id = p_league_id
  for update;

  if not found then
    raise exception 'League could not be found.';
  end if;

  if v_history_id is null then
    insert into public.nhl_pickem_histories default values
    returning id into v_history_id;

    update public.leagues
    set nhl_pickem_history_id = v_history_id,
        updated_at = now()
    where id = p_league_id;
  end if;

  return v_history_id;
end;
$$;

