  public.get_g365_nhl_favorite_puck_line(-120) = -0.5
  and public.get_g365_nhl_favorite_puck_line(-175) = -1.0
  and public.get_g365_nhl_favorite_puck_line(-225) = -1.5
  and public.get_g365_nhl_favorite_puck_line(-275) = -2.0
  and public.get_g365_nhl_favorite_puck_line(-325) = -2.5
  as pass;

select
  'nhl_pickem_realtime' as check_name,
  count(*) = 5 as pass,
  count(*) as found_count
from pg_publication_tables
where pubname = 'supabase_realtime'
  and schemaname = 'public'
  and tablename in (
    'nhl_pickem_periods',
    'nhl_pickem_games',
    'nhl_pickem_entries',
    'nhl_pickem_picks',
    'nhl_pickem_standings'
  );