-- -----------------------------------------------------------------------------
-- Same-game market restriction
-- -----------------------------------------------------------------------------

create or replace function private.enforce_nhl_pickem_same_game_market_rule()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_allow boolean;
begin
  select s.allow_same_game_multiple_markets
    into v_allow
  from public.nhl_pickem_settings s
  where s.league_id = new.league_id;

  if coalesce(v_allow, false) = false then
    if exists (
      select 1
      from public.nhl_pickem_picks p
      where p.entry_id = new.entry_id
        and p.nhl_pickem_period_id = new.nhl_pickem_period_id
        and p.nhl_pickem_game_id = new.nhl_pickem_game_id
        and p.id <> coalesce(new.id, -1)
    ) then
      raise exception 'This league allows only one market pick per NHL game.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_nhl_pickem_same_game_market_rule
  on public.nhl_pickem_picks;
