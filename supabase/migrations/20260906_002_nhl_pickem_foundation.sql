create or replace function public.get_g365_nhl_favorite_puck_line(
  p_favorite_moneyline numeric
)
returns numeric
language plpgsql
immutable
security invoker
set search_path = public, pg_temp
as $$
begin
  if p_favorite_moneyline is null then
    return null;
  elsif p_favorite_moneyline <= -300 then
    return -2.5;
  elsif p_favorite_moneyline <= -250 then
    return -2.0;
  elsif p_favorite_moneyline <= -200 then
    return -1.5;
  elsif p_favorite_moneyline <= -150 then
    return -1.0;
  elsif p_favorite_moneyline <= -100 then
    return -0.5;
  else
    return null;
  end if;
end;
$$;

