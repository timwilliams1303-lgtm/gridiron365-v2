-- -----------------------------------------------------------------------------
-- Prevent picks after puck drop; snapshot frozen official lines.
-- -----------------------------------------------------------------------------

create or replace function private.prepare_nhl_pickem_pick()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_game record;
begin
  select
    pg.id,
    pg.is_frozen,
    pg.official_home_puck_line,
    pg.official_away_puck_line,
    pg.official_total,
    ng.kickoff_at
  into v_game
  from public.nhl_pickem_games pg
  join public.nhl_games ng on ng.id = pg.nhl_game_id
  where pg.id = new.nhl_pickem_game_id;

  if not found then
    raise exception 'NHL Pick''em game could not be found.';
  end if;

  if not v_game.is_frozen then
    raise exception 'G365 NHL Pick''em lines are not frozen for this game yet.';
  end if;

  if now() >= v_game.kickoff_at then
    raise exception 'This NHL Pick''em game has already locked at puck drop.';
  end if;

  new.snapshot_home_puck_line := v_game.official_home_puck_line;
  new.snapshot_away_puck_line := v_game.official_away_puck_line;
  new.snapshot_total := v_game.official_total;

  return new;
end;
$$;

